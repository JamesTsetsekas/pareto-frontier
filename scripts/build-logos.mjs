#!/usr/bin/env node
// Builds assets/logos.svg: an SVG sprite of provider logos from LobeHub Icons
// (MIT, https://github.com/lobehub/lobe-icons). Run manually when adding a
// provider; the output is committed so the site has no runtime dependency.

import { writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const VERSION = "1.104.0";
const CDN = `https://cdn.jsdelivr.net/npm/@lobehub/icons-static-svg@${VERSION}/icons`;
const OUT = resolve(dirname(fileURLToPath(import.meta.url)), "../assets/logos.svg");

// Icon names used by assets/app.js (PROVIDER_LOGO). Mono icons use currentColor.
const ICONS = [
  "openai", "anthropic", "google-color", "xai", "deepseek-color", "kimi-color",
  "qwen-color", "meta-color", "mistral-color", "minimax-color", "zai",
  "nvidia-color", "reflection", "inception", "dotsstudio",
];

// Not in LobeHub: a simple person glyph for the human baseline.
const EXTRA = {
  human: `<circle cx="12" cy="7" r="4" fill="currentColor"/><path d="M4 21c0-4.4 3.6-8 8-8s8 3.6 8 8z" fill="currentColor"/>`,
};

function toSymbol(name, svg) {
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1] || "0 0 24 24";
  const rootFill = svg.match(/^<svg[^>]*\sfill="([^"]+)"/)?.[1];
  let inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
  inner = inner.replace(/<title>[\s\S]*?<\/title>/g, "");
  // Gradient ids must stay unique once every icon shares one document.
  inner = inner.replace(/id="([^"]+)"/g, `id="${name}-$1"`).replace(/url\(#([^)]+)\)/g, `url(#${name}-$1)`);
  const rootRule = svg.match(/^<svg[^>]*\sfill-rule="([^"]+)"/)?.[1];
  const attrs = (rootFill ? ` fill="${rootFill}"` : "") + (rootRule ? ` fill-rule="${rootRule}"` : "");
  return `<symbol id="logo-${name}" viewBox="${viewBox}"${attrs}>${inner}</symbol>`;
}

const symbols = [];
for (const name of ICONS) {
  const res = await fetch(`${CDN}/${name}.svg`);
  if (!res.ok) throw new Error(`${name}: HTTP ${res.status}`);
  symbols.push(toSymbol(name, (await res.text()).trim()));
}
for (const [name, body] of Object.entries(EXTRA)) {
  symbols.push(`<symbol id="logo-${name}" viewBox="0 0 24 24">${body}</symbol>`);
}

const sprite = `<!-- Provider logos from LobeHub Icons v${VERSION} (MIT). Generated by scripts/build-logos.mjs. -->
<svg xmlns="http://www.w3.org/2000/svg" style="display:none">${symbols.join("")}</svg>
`;
await writeFile(OUT, sprite);
console.log(`Wrote ${OUT} (${symbols.length} logos, ${sprite.length} bytes)`);
